package jd.core.process.analyzer.instruction.fast;

import org.apache.bcel.classfile.CodeException;
import org.apache.bcel.classfile.ConstantCP;
import org.apache.bcel.classfile.ConstantClass;
import org.apache.bcel.classfile.ConstantNameAndType;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import jd.core.model.classfile.ConstantPool;
import jd.core.model.classfile.LocalVariable;
import jd.core.model.classfile.LocalVariables;
import jd.core.model.classfile.Method;
import jd.core.model.instruction.bytecode.ByteCodeConstants;
import jd.core.model.instruction.bytecode.instruction.ALoad;
import jd.core.model.instruction.bytecode.instruction.AStore;
import jd.core.model.instruction.bytecode.instruction.AThrow;
import jd.core.model.instruction.bytecode.instruction.ExceptionLoad;
import jd.core.model.instruction.bytecode.instruction.Goto;
import jd.core.model.instruction.bytecode.instruction.IfInstruction;
import jd.core.model.instruction.bytecode.instruction.Instruction;
import jd.core.model.instruction.bytecode.instruction.InvokeNoStaticInstruction;
import jd.core.process.analyzer.util.InstructionUtil;

/**
 * Normalizes the try-with-resources code generated by javac 11 and later.
 * <p>
 * Contrary to javac 7/8, these compilers do not use a "primary exception" variable. For a resource
 * <code>r</code> the generated code looks like this (the null checks are only present when the
 * resource initializer is not a constructor call):
 * </p>
 * <pre>
 * r = ...;
 * try {
 *     body
 * } catch (Throwable t) {
 *     if (r != null) {
 *         try { r.close(); } catch (Throwable t2) { t.addSuppressed(t2); }
 *     }
 *     throw t;
 * }
 * if (r != null) r.close();
 * </pre>
 * This class rewrites it to a plain <code>try { body } catch (Throwable t) { throw t; }</code> by
 * removing the closing code and its exception table entry. The variable <code>r</code> is flagged
 * so that the {@link FastInstructionListBuilder} can turn the resulting try block into a
 * try-with-resources statement.
 */
final class ModernTryWithResourcesNormalizer {

    private static final String THROWABLE = "java/lang/Throwable";

    private ModernTryWithResourcesNormalizer() {
    }

    static void normalize(Method method, ConstantPool cp, List<Instruction> list) {
        CodeException[] codeExceptions = method.getCodeExceptions();
        LocalVariables localVariables = method.getLocalVariables();
        if (codeExceptions == null || codeExceptions.length < 2 || localVariables == null) {
            return;
        }
        List<CodeException> remaining = new ArrayList<>(Arrays.asList(codeExceptions));
        boolean changed = false;
        for (CodeException outer : codeExceptions) {
            if (!remaining.contains(outer) || !isThrowable(cp, outer)) {
                continue;
            }
            changed |= normalize(cp, list, localVariables, remaining, outer);
        }
        if (changed) {
            method.setCodeExceptions(remaining.toArray(new CodeException[0]));
        }
    }

    private static boolean normalize(ConstantPool cp, List<Instruction> list, LocalVariables localVariables,
            List<CodeException> remaining, CodeException outer) {
        int handlerIndex = indexOfOffset(list, outer.getHandlerPC());
        if (handlerIndex < 1 || !(list.get(handlerIndex) instanceof AStore storeThrowable)
                || !(storeThrowable.getValueref() instanceof ExceptionLoad)) {
            return false;
        }
        int next = handlerIndex + 1;
        if (next >= list.size()) {
            return false;
        }

        // Optional null check of the resource
        int resourceIndex = -1;
        if (list.get(next) instanceof IfInstruction ifNull && isNullCheck(ifNull)) {
            resourceIndex = ((ALoad) ifNull.getValue()).getIndex();
            next++;
        }

        // r.close() protected by the inner exception table entry
        if (next >= list.size() || !(list.get(next) instanceof InvokeNoStaticInstruction close)
                || !isMethod(cp, close, "close", "()V") || !(close.getObjectref() instanceof ALoad closeTarget)
                || resourceIndex != -1 && resourceIndex != closeTarget.getIndex()) {
            return false;
        }
        resourceIndex = closeTarget.getIndex();
        next++;

        // goto to the throw instruction
        if (next >= list.size() || !(list.get(next) instanceof Goto)) {
            return false;
        }
        next++;

        // catch (Throwable t2)
        if (next >= list.size() || !(list.get(next) instanceof AStore storeSuppressed)
                || !(storeSuppressed.getValueref() instanceof ExceptionLoad)) {
            return false;
        }
        CodeException inner = null;
        for (CodeException ce : remaining) {
            if (ce.getHandlerPC() == storeSuppressed.getOffset() && isThrowable(cp, ce)) {
                inner = ce;
            }
        }
        if (inner == null) {
            return false;
        }
        next++;

        // t.addSuppressed(t2)
        if (next >= list.size() || !(list.get(next) instanceof InvokeNoStaticInstruction addSuppressed)
                || !isMethod(cp, addSuppressed, "addSuppressed", "(Ljava/lang/Throwable;)V")
                || !(addSuppressed.getObjectref() instanceof ALoad suppressedTarget)
                || suppressedTarget.getIndex() != storeThrowable.getIndex()
                || addSuppressed.getArgs().size() != 1
                || !(addSuppressed.getArgs().get(0) instanceof ALoad suppressedArg)
                || suppressedArg.getIndex() != storeSuppressed.getIndex()) {
            return false;
        }
        next++;

        // throw t
        if (next >= list.size() || !(list.get(next) instanceof AThrow athrow)
                || !(athrow.getValue() instanceof ALoad thrown) || thrown.getIndex() != storeThrowable.getIndex()) {
            return false;
        }
        int throwIndex = next;

        // The resource is stored just before the protected region
        int startIndex = InstructionUtil.getIndexForOffset(list, outer.getStartPC());
        if (startIndex < 1 || !(list.get(startIndex - 1) instanceof AStore storeResource)
                || storeResource.getIndex() != resourceIndex || storeResource.getValueref() instanceof ExceptionLoad) {
            return false;
        }
        LocalVariable resource = localVariables.getLocalVariableWithIndexAndOffset(storeResource.getIndex(),
                storeResource.getOffset());
        if (resource == null) {
            return false;
        }

        // A genuine try-with-resources always closes the resource after the protected region.
        // Hand written code that only mimics the exceptional path is left untouched.
        List<Integer> normalPathCloses = findNormalPathCloses(cp, list, remaining, outer, resourceIndex);
        if (normalPathCloses.isEmpty()) {
            return false;
        }

        // Remove the closing code of the exceptional path, only 'catch (Throwable t) { throw t; }' is kept
        list.subList(handlerIndex + 1, throwIndex).clear();
        remaining.remove(inner);

        // Remove the closing code of the normal path (not protected by the exception table)
        removeNormalPathCloses(list, normalPathCloses, resourceIndex);

        resource.setModernTryResource(true);
        return true;
    }

    /** @return indexes of the compiler generated 'r.close()' calls of the normal path, in descending order */
    private static List<Integer> findNormalPathCloses(ConstantPool cp, List<Instruction> list,
            List<CodeException> remaining, CodeException outer, int resourceIndex) {
        List<Integer> indexes = new ArrayList<>();
        int handlerPc = outer.getHandlerPC();
        for (int i = list.size() - 1; i >= 0; i--) {
            Instruction instruction = list.get(i);
            int offset = instruction.getOffset();
            if (offset >= outer.getStartPC() && offset < handlerPc
                    && instruction instanceof InvokeNoStaticInstruction close && isMethod(cp, close, "close", "()V")
                    && close.getObjectref() instanceof ALoad target && target.getIndex() == resourceIndex
                    && !isProtected(remaining, handlerPc, offset)) {
                indexes.add(i);
            }
        }
        return indexes;
    }

    private static void removeNormalPathCloses(List<Instruction> list, List<Integer> indexes, int resourceIndex) {
        for (int i : indexes) {
            list.remove(i);
            if (i > 0 && list.get(i - 1) instanceof IfInstruction ifNull && isNullCheck(ifNull)
                    && ((ALoad) ifNull.getValue()).getIndex() == resourceIndex) {
                list.remove(i - 1);
            }
        }
    }

    private static boolean isProtected(List<CodeException> remaining, int handlerPc, int offset) {
        for (CodeException ce : remaining) {
            if (ce.getHandlerPC() == handlerPc && ce.getStartPC() <= offset && offset < ce.getEndPC()) {
                return true;
            }
        }
        return false;
    }

    /** @return true for 'if (r == null) goto ...' */
    private static boolean isNullCheck(IfInstruction instruction) {
        return instruction.getOpcode() == ByteCodeConstants.IFXNULL && instruction.getCmp() == ByteCodeConstants.CMP_EQ
                && instruction.getValue() instanceof ALoad;
    }

    private static boolean isThrowable(ConstantPool cp, CodeException codeException) {
        int catchType = codeException.getCatchType();
        if (catchType == 0) {
            return false;
        }
        ConstantClass constantClass = cp.getConstantClass(catchType);
        return THROWABLE.equals(cp.getConstantUtf8(constantClass.getNameIndex()));
    }

    private static boolean isMethod(ConstantPool cp, InvokeNoStaticInstruction invoke, String name, String descriptor) {
        ConstantCP methodref = cp.getConstantMethodref(invoke.getIndex());
        ConstantNameAndType nameAndType = cp.getConstantNameAndType(methodref.getNameAndTypeIndex());
        return name.equals(cp.getConstantUtf8(nameAndType.getNameIndex()))
                && descriptor.equals(cp.getConstantUtf8(nameAndType.getSignatureIndex()));
    }

    private static int indexOfOffset(List<Instruction> list, int offset) {
        for (int i = 0; i < list.size(); i++) {
            if (list.get(i).getOffset() == offset) {
                return i;
            }
        }
        return -1;
    }
}
