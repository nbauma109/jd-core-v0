/**
 * Normalizes the try-with-resources code generated by javac 11 and later.
 * <p>
 * Contrary to javac 7/8, these compilers do not use a "primary exception" variable. For a resource
 * <code>r</code> the generated code looks like this (the null checks are only present when the
 * resource initializer is not a constructor call):
 * </p>
 * <pre>
 * r = ...;
 * try {
 *     body
 * } catch (Throwable t) {
 *     if (r != null) {
 *         try { r.close(); } catch (Throwable t2) { t.addSuppressed(t2); }
 *     }
 *     throw t;
 * }
 * if (r != null) r.close();
 * </pre>
 * This class rewrites it to a plain <code>try { body } catch (Throwable t) { throw t; }</code> by
 * removing the closing code and its exception table entry. The variable <code>r</code> is flagged
 * so that the {@link FastInstructionListBuilder} can turn the resulting try block into a
 * try-with-resources statement.
 */
final class ModernTryWithResourcesNormalizer {

    private static final String THROWABLE = "java/lang/Throwable";
    private static final String AUTO_CLOSEABLE = "java/lang/AutoCloseable";

    private ModernTryWithResourcesNormalizer() {
    }

    static void normalize(Method method, ConstantPool cp, Loader loader, List<Instruction> list) {
        CodeException[] codeExceptions = method.getCodeExceptions();
        LocalVariables localVariables = method.getLocalVariables();
        if (ArrayUtils.getLength(codeExceptions) < 2 || localVariables == null) {
            return;
        }
        List<CodeException> remaining = new ArrayList<>(Arrays.asList(codeExceptions));
        boolean changed = false;
        for (CodeException outer : codeExceptions) {
            if (!remaining.contains(outer) || !isThrowable(cp, outer)) {
                continue;
            }
            changed |= normalize(cp, loader, list, localVariables, remaining, outer);
        }
        if (changed) {
            method.setCodeExceptions(remaining.toArray(new CodeException[0]));
        }
    }

    /** Position of the closing code in the handler of the protected region, and the variables it uses. */
    private record Handler(int throwIndex, int resourceIndex, String resourceType, CodeException inner) {
    }

    private static boolean normalize(ConstantPool cp, Loader loader, List<Instruction> list,
            LocalVariables localVariables, List<CodeException> remaining, CodeException outer) {
        int handlerIndex = indexOfOffset(list, outer.getHandlerPC());
        Handler handler = parseHandler(cp, list, remaining, handlerIndex);
        if (handler == null) {
            return false;
        }

        // The resource is stored just before the protected region
        int startIndex = InstructionUtil.getIndexForOffset(list, outer.getStartPC());
        if (startIndex < 1 || !(list.get(startIndex - 1) instanceof AStore storeResource)
                || storeResource.getIndex() != handler.resourceIndex()) {
            return false;
        }
        LocalVariable resource = localVariables.getLocalVariableWithIndexAndOffset(storeResource.getIndex(),
                storeResource.getOffset());
        // Cleanup written by hand: the resource is not an AutoCloseable, or it is another value when it is closed
        if (resource == null || isKnownNotAutoCloseable(loader, handler.resourceType())
                || storesLocal(list, startIndex, handlerIndex, handler.resourceIndex())) {
            return false;
        }

        // A genuine try-with-resources closes the resource after the protected region, unless the body never completes
        // normally. Hand written code that only mimics the exceptional path is left untouched.
        List<Integer> normalPathCloses = findNormalPathCloses(cp, list, remaining, outer, handler.resourceIndex());
        if (normalPathCloses.isEmpty() && (!cannotFallIntoHandler(list.get(handlerIndex - 1))
                || hasNormalExit(list, startIndex, handlerIndex, outer.getHandlerPC()))) {
            return false;
        }

        // The variable becomes the one of a resource specification: it cannot be used out of the try statement
        if (isUsedOutside(list, localVariables, resource, handler.resourceIndex(), startIndex, handler.throwIndex(),
                normalPathCloses)) {
            return false;
        }

        // Only the catch of Throwable that rethrows is kept: the closing code of the exceptional path is removed
        list.subList(handlerIndex + 1, handler.throwIndex()).clear();
        remaining.remove(handler.inner());

        // Remove the closing code of the normal path (not protected by the exception table)
        removeNormalPathCloses(list, normalPathCloses, handler.resourceIndex());

        resource.setModernTryResource(true);
        return true;
    }

    /**
     * Recognizes the handler: optional null check, close of the resource, goto, handler of the close,
     * addSuppressed and rethrow.
     *
     * @return null if the handler has another shape
     */
    private static Handler parseHandler(ConstantPool cp, List<Instruction> list, List<CodeException> remaining,
            int handlerIndex) {
        if (handlerIndex < 1 || !isExceptionStore(list.get(handlerIndex))) {
            return null;
        }
        AStore storeThrowable = (AStore) list.get(handlerIndex);
        int next = handlerIndex + 1;

        // Optional null check of the resource
        int resourceIndex = nullCheckedIndex(list.get(next));
        if (resourceIndex != -1) {
            next++;
        }

        // The close of the resource is protected by the inner exception table entry
        int closeIndex = next;
        int closedIndex = closedResourceIndex(cp, at(list, next));
        if (closedIndex == -1 || resourceIndex != -1 && resourceIndex != closedIndex) {
            return null;
        }
        next++;

        // goto to the throw instruction, then the handler of the close
        if (!(at(list, next) instanceof Goto) || !isExceptionStore(at(list, next + 1))) {
            return null;
        }
        AStore storeSuppressed = (AStore) list.get(next + 1);
        CodeException inner = findHandlerOf(cp, remaining, storeSuppressed.getOffset());
        next += 2;

        if (inner == null || !isAddSuppressed(cp, at(list, next), storeThrowable.getIndex(), storeSuppressed.getIndex())
                || loadedIndex(at(list, next + 1) instanceof AThrow athrow ? athrow.getValue() : null) != storeThrowable.getIndex()) {
            return null;
        }
        return new Handler(next + 1, closedIndex, closedOwner(cp, at(list, closeIndex)), inner);
    }

    /** A return, or a jump to the code after the handler, leaves the protected region without closing the resource. */
    private static boolean hasNormalExit(List<Instruction> list, int startIndex, int handlerIndex, int handlerPc) {
        for (int i = startIndex; i < handlerIndex; i++) {
            Instruction instruction = list.get(i);
            if (instruction instanceof ReturnInstruction || instruction instanceof Return
                    || instruction instanceof BranchInstruction branch && branch.getJumpOffset() >= handlerPc) {
                return true;
            }
        }
        return false;
    }

    /**
     * @return true if the variable is loaded out of the protected region and its handler, except by the closing code of
     *         the normal path (and its null check), that is removed
     */
    private static boolean isUsedOutside(List<Instruction> list, LocalVariables localVariables, LocalVariable resource,
            int index, int firstIndex, int lastIndex, List<Integer> normalPathCloses) {
        SearchInstructionByTypeVisitor<LoadInstruction> loads = new SearchInstructionByTypeVisitor<>(LoadInstruction.class,
                load -> load.getIndex() == index
                        && localVariables.getLocalVariableWithIndexAndOffset(index, load.getOffset()) == resource);
        for (int i = 0; i < list.size(); i++) {
            boolean removed = normalPathCloses.contains(i) || normalPathCloses.contains(i + 1) && nullCheckedIndex(list.get(i)) == index;
            if ((i < firstIndex || i > lastIndex) && !removed && loads.visit(list.get(i)) != null) {
                return true;
            }
        }
        return false;
    }

    /** @return the class on which close() is called, as the call names it */
    private static String closedOwner(ConstantPool cp, Instruction close) {
        return cp.getConstantClassName(cp.getConstantMethodref(((InvokeNoStaticInstruction) close).getIndex()).getClassIndex());
    }

    /** The resource is stored again in the protected region: it is not the variable of a resource specification. */
    private static boolean storesLocal(List<Instruction> list, int startIndex, int handlerIndex, int index) {
        for (int i = startIndex; i < handlerIndex; i++) {
            if (list.get(i) instanceof AStore store && store.getIndex() == index) {
                return true;
            }
        }
        return false;
    }

    /**
     * A resource is an AutoCloseable: code that closes an object of another class is hand written cleanup.
     * A class that cannot be loaded is supposed to be the one that the compiler checked.
     */
    private static boolean isKnownNotAutoCloseable(Loader loader, String type) {
        Deque<String> todo = new ArrayDeque<>();
        Set<String> seen = new HashSet<>();
        todo.push(type);
        while (!todo.isEmpty()) {
            String name = todo.pop();
            if (!seen.add(name)) {
                continue;
            }
            if (AUTO_CLOSEABLE.equals(name)) {
                return false;
            }
            JavaClass javaClass = parse(loader, name);
            if (javaClass == null) {
                return false;
            }
            todo.push(javaClass.getSuperclassName().replace('.', '/'));
            for (String implemented : javaClass.getInterfaceNames()) {
                todo.push(implemented.replace('.', '/'));
            }
        }
        return true;
    }

    private static JavaClass parse(Loader loader, String name) {
        String entry = name + StringConstants.CLASS_FILE_SUFFIX;
        try {
            return loader.canLoad(entry) ? new ClassParser(new ByteArrayInputStream(loader.load(entry)), entry).parse() : null;
        } catch (IOException e) { return null; }
    }

    /** The body ends with a throw or a jump back (an endless loop): the code after the region is not reached. */
    private static boolean cannotFallIntoHandler(Instruction last) {
        return last instanceof AThrow || last instanceof Goto jump && jump.getBranch() <= 0;
    }

    /** @return the instruction at the index, or null after the end of the list */
    private static Instruction at(List<Instruction> list, int index) {
        return index < list.size() ? list.get(index) : null;
    }

    /** @return the index of the local variable loaded by the instruction, or -1 */
    private static int loadedIndex(Instruction instruction) {
        return instruction instanceof ALoad load ? load.getIndex() : -1;
    }

    private static boolean isExceptionStore(Instruction instruction) {
        return instruction instanceof AStore store && store.getValueref() instanceof ExceptionLoad;
    }

    /** @return the index of the variable on which close() is called, or -1 */
    private static int closedResourceIndex(ConstantPool cp, Instruction instruction) {
        return instruction instanceof InvokeNoStaticInstruction close && isMethod(cp, close, "close", "()V")
                ? loadedIndex(close.getObjectref()) : -1;
    }

    private static CodeException findHandlerOf(ConstantPool cp, List<CodeException> remaining, int handlerPc) {
        CodeException found = null;
        for (CodeException ce : remaining) {
            if (ce.getHandlerPC() == handlerPc && isThrowable(cp, ce)) {
                found = ce;
            }
        }
        return found;
    }

    private static boolean isAddSuppressed(ConstantPool cp, Instruction instruction, int throwableIndex,
            int suppressedIndex) {
        return instruction instanceof InvokeNoStaticInstruction call
                && isMethod(cp, call, "addSuppressed", "(Ljava/lang/Throwable;)V")
                && loadedIndex(call.getObjectref()) == throwableIndex
                && loadedIndex(call.getArgs().get(0)) == suppressedIndex;
    }

    /** @return indexes of the compiler generated 'r.close()' calls of the normal path, in descending order */
    private static List<Integer> findNormalPathCloses(ConstantPool cp, List<Instruction> list,
            List<CodeException> remaining, CodeException outer, int resourceIndex) {
        List<Integer> indexes = new ArrayList<>();
        int handlerPc = outer.getHandlerPC();
        for (int i = list.size() - 1; i >= 0; i--) {
            Instruction instruction = list.get(i);
            int offset = instruction.getOffset();
            if (offset >= outer.getStartPC() && offset < handlerPc
                    && closedResourceIndex(cp, instruction) == resourceIndex
                    && !isProtected(remaining, handlerPc, offset)) {
                indexes.add(i);
            }
        }
        return indexes;
    }

    private static void removeNormalPathCloses(List<Instruction> list, List<Integer> indexes, int resourceIndex) {
        for (int i : indexes) {
            list.remove(i);
            if (i > 0 && nullCheckedIndex(list.get(i - 1)) == resourceIndex) {
                list.remove(i - 1);
            }
        }
    }

    private static boolean isProtected(List<CodeException> remaining, int handlerPc, int offset) {
        for (CodeException ce : remaining) {
            if (ce.getHandlerPC() == handlerPc && ce.getStartPC() <= offset && offset < ce.getEndPC()) {
                return true;
            }
        }
        return false;
    }

    /** @return the index of the variable r in 'if (r == null) goto ...', or -1 */
    private static int nullCheckedIndex(Instruction instruction) {
        return instruction instanceof IfInstruction ifNull && ifNull.getOpcode() == ByteCodeConstants.IFXNULL
                && ifNull.getCmp() == ByteCodeConstants.CMP_EQ ? loadedIndex(ifNull.getValue()) : -1;
    }

    private static boolean isThrowable(ConstantPool cp, CodeException codeException) {
        int catchType = codeException.getCatchType();
        if (catchType == 0) {
            return false;
        }
        ConstantClass constantClass = cp.getConstantClass(catchType);
        return THROWABLE.equals(cp.getConstantUtf8(constantClass.getNameIndex()));
    }

    private static boolean isMethod(ConstantPool cp, InvokeNoStaticInstruction invoke, String name, String descriptor) {
        ConstantCP methodref = cp.getConstantMethodref(invoke.getIndex());
        ConstantNameAndType nameAndType = cp.getConstantNameAndType(methodref.getNameAndTypeIndex());
        return name.equals(cp.getConstantUtf8(nameAndType.getNameIndex()))
                && descriptor.equals(cp.getConstantUtf8(nameAndType.getSignatureIndex()));
    }

    private static int indexOfOffset(List<Instruction> list, int offset) {
        for (int i = 0; i < list.size(); i++) {
            if (list.get(i).getOffset() == offset) {
                return i;
            }
        }
        return -1;
    }
}
